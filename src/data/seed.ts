export function makeOrder(type: OrderType = '接稿'): Order {
  return {
    ...entity(),
    name: '',
    type,
    queuePosition: Date.now(),
    counterpartyId: null,
    customType: '',
    number: '',
    platform: '',
    description: '',
    party: '',
    contact: '',
    shopUrl: '',
    communication: '',
    amount: null,
    platformFeeMode: 'fixed',
    platformFee: 0,
    platformColor: '',
    cashFlow: defaultFlow(type),
    deposit: null,
    balance: null,
    payment: '未付款',
    refund: '无退款',
    startDate: dateKey(),
    dueDate: '',
    deliveryDate: '',
    actualDeliveryDate: '',
    shipDate: '',
    receiveDate: '',
    completedDate: '',
    status: '待处理',
    stage: 0,
    steps: stepsFor(type),
    archived: false,
    attachments: [],
    notes: '',
    links: '',
    history: [],
  };
}
export function makeFolder(parentId: string | null = null): Folder {
  return {
    ...entity(),
    ...reviewFields(),
    name: '',
    parentId,
    description: '',
    tags: [],
    purpose: '普通文件夹',
    cover: [],
    archived: false,
    merchant: '',
    shopUrl: '',
    contact: '',
    experience: '',
    service: '',
    packaging: '',
    shipping: '',
  };
}
export function makeItem(folderId: string | null = null): Item {
  return {
    calendarEnabled: false,
    tradeKind: 'purchase',
    startDate: dateKey(),
    dueDate: '',
    platformColor: '',
    ...entity(),
    ...reviewFields(),
    name: '',
    folderId,
    description: '',
    tags: [],
    spec: '',
    quantity: 1,
    merchant: '',
    platform: '',
    purchaseDate: '',
    price: null,
    productUrl: '',
    location: '',
    notes: '',
    experience: '',
    featured: false,
    archived: false,
    attachments: [],
    illustration: '',
  };
}
export function makeTask(date = dateKey(), orderId: string | null = null): Task {
  return {
    ...entity(),
    name: '',
    orderId,
    date,
    time: '',
    done: false,
    notes: '',
    position: Date.now(),
    reminder: { enabled: false, at: '' },
  };
}
